// Rebuilds the Pixel TV art with pxl and embeds it into tv/index.html (between the ART markers).
// Usage:  node tv/art/embed.mjs <path to a clone of github.com/crsolver/claude-pxl>
// The deployed page stays a single self-contained file: the PNGs go in as data URIs.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pxl = process.argv[2];
if (!pxl) { console.error('usage: node tv/art/embed.mjs <path to claude-pxl>'); process.exit(1); }

const out = fs.mkdtempSync(path.join(os.tmpdir(), 'pxl-tv-'));
execFileSync('node', [path.join(pxl, 'bin', 'pxl.js'), 'build', path.join(here, 'lunch-break.px.js'), '--out', out, '--no-preview'], { stdio: 'inherit' });

const uri = f => 'data:image/png;base64,' + fs.readFileSync(path.join(out, f)).toString('base64');
const sheet = JSON.parse(fs.readFileSync(path.join(out, 'chars.json'), 'utf8'));
const frames = {};
for (const [name, v] of Object.entries(sheet.frames)) { const f = v.frame; frames[name.replace(/\.png$/, '')] = [f.x, f.y, f.w, f.h]; }

const art = {
  sets: {
    fire: { back: uri('scenes/fire.png'), front: uri('scenes/fire_front.png') },
    apt: { back: uri('scenes/apt.png'), front: uri('scenes/apt_front.png') }
  },
  chars: { sheet: uri('chars.png'), frames }
};

const file = path.join(here, '..', 'index.html');
const html = fs.readFileSync(file, 'utf8');
const re = /\/\*ART:BEGIN[\s\S]*?\/\*ART:END\*\//;
if (!re.test(html)) { console.error('ART markers not found in tv/index.html'); process.exit(1); }
const block = '/*ART:BEGIN generated by tv/art/embed.mjs from tv/art/lunch-break.px.js — do not edit by hand*/\n' +
  'const ART = ' + JSON.stringify(art) + ';\n/*ART:END*/';
fs.writeFileSync(file, html.replace(re, () => block));
console.log('embedded art:', Object.keys(frames).length, 'character frames,', (block.length / 1024).toFixed(1), 'KB');
